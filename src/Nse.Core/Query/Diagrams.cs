using System.Globalization;
using System.Text;
using Nse.Model;

namespace Nse.Query;

/// <summary>
/// The story at a glance. Every view is generated from the records, never edited by
/// hand, and the same bytes every time it is generated from the same ledger and manuscript. Each is Markdown, with
/// Mermaid where a picture says more than a table, so it renders on GitHub and in most editors.
/// </summary>
public static class Diagrams
{
    public static readonly string[] Views = ["knowledge", "secrets", "objects", "divergence"];

    public static string Text(StoryState s, string view, string? holder = null)
    {
        ArgumentNullException.ThrowIfNull(s);
        return view switch
        {
            "knowledge" => Knowledge(s, holder ?? throw new ArgumentException("the knowledge view is of one person: give a holder")),
            "secrets" => Secrets(s),
            "objects" => Objects(s),
            "divergence" => Divergence(s),
            _ => throw new ArgumentException($"there is no view '{view}'. The views are: {string.Join(", ", Views)}"),
        };
    }

    /// <summary>A cell of a Markdown table: no bar, and no line break, can come through from a record.</summary>
    private static string Cell(string? text) => Nse.Text.Plain.OneLine(text).Replace("|", "\\|", StringComparison.Ordinal);

    private static string Num(double key) => double.IsNegativeInfinity(key) ? "outset" : key.ToString(CultureInfo.InvariantCulture);

    private static IReadOnlyList<Manuscript.ManuscriptScene> Timed(StoryState s) =>
        s.Telling.Where(t => s.Model.SceneTimes.ContainsKey(t.Id) && s.Model.Scenes.ContainsKey(t.Id)).ToList();

    private static string Header(StoryState s, string title) =>
        $"# {title}\n\nGenerated by `nse diagram` from ledger head {s.Model.Head} and manuscript {s.ManuscriptHash[..Math.Min(12, s.ManuscriptHash.Length)]}. Do not edit: generate it again.\n\n";

    /// <summary>One person's view of every fact worth guarding, on entry to each scene in the order they are told.</summary>
    private static string Knowledge(StoryState s, string holder)
    {
        var person = s.Model.Base(holder);
        if (s.Model.Entity(person) is not { Type: EntityKind.Character } who)
            throw new KeyNotFoundException($"{holder} is not a person in the ledger.");
        var scenes = Timed(s);
        var props = s.Model.Propositions.Where(p => s.Guarded(p.Id) || s.Model.BeliefsOf(person, p.Id).Count > 0).Select(p => p.Id).ToList();
        var sb = new StringBuilder(Header(s, $"What {Cell(who.Name)} knows, scene by scene"));
        sb.Append("On entry to each scene, in the order the scenes are told. ")
          .Append("K knows; k right, but less than certain; F false belief; O outdated belief; U unaware; D undecided; ? not settled; · nothing recorded either way, which is not the same as unaware.\n\n");
        sb.Append("| Fact |").Append(string.Concat(scenes.Select(t => $" {t.Tell} |"))).Append('\n');
        sb.Append("|---|").Append(string.Concat(scenes.Select(_ => "---|"))).Append('\n');
        foreach (var prop in props)
        {
            sb.Append(CultureInfo.InvariantCulture, $"| {prop} |");
            foreach (var t in scenes)
            {
                var key = s.Key(t.Id);
                var label = s.Classify(s.BeliefBefore(person, prop, key), key);
                sb.Append(' ').Append(Code(label)).Append(" |");
            }
            sb.Append('\n');
        }
        sb.Append("\nScenes: ").Append(string.Join("; ", scenes.Select(t => $"{t.Tell} {t.Id}"))).Append(".\n\nFacts:\n");
        foreach (var prop in props)
            sb.Append(CultureInfo.InvariantCulture, $"- {prop}: {Cell(s.Model.Proposition(prop)!.Text)}\n");
        return sb.ToString();
    }

    private static string Code(string label) => label switch
    {
        "no record" => "·",
        "knows" or "knows it is false" => "K",
        "FALSE BELIEF" => "F",
        "OUTDATED BELIEF" => "O",
        "unaware" => "U",
        "undecided" => "D",
        _ when label.StartsWith("correctly", StringComparison.Ordinal) => "k",
        _ => "?",
    };

    /// <summary>For each fact worth guarding: when it came about, when the reader is told, and when each person first gets it right.</summary>
    private static string Secrets(StoryState s)
    {
        var props = s.Model.Propositions.Where(p => s.Guarded(p.Id)).Select(p => p.Id).ToList();
        var people = s.Holders;
        var sb = new StringBuilder(Header(s, "Who learns what, and when"));
        sb.Append("For each fact worth guarding: the story time from which it is so, the scene in which the reader is first told it, and the story time at which each person first gets it right, with the scene where that is on the page. A dash: never, as recorded.\n\n");
        sb.Append("| Fact | So from | Reader told in |").Append(string.Concat(people.Select(p => $" {Cell(s.Short(p))} |"))).Append('\n');
        sb.Append("|---|---|---|").Append(string.Concat(people.Select(_ => "---|"))).Append('\n');
        foreach (var prop in props)
        {
            var canon = s.Canon(prop);
            var so = s.Model.Facts(prop).Where(f => f.Value == (canon == "true")).Select(f => f.StoryKey ?? double.NegativeInfinity).DefaultIfEmpty(double.NaN).Min();
            var reveal = s.RevealScene(prop);
            sb.Append(CultureInfo.InvariantCulture,
                $"| {prop}{(canon == "false" ? " (not so)" : "")} | {(double.IsNaN(so) ? "-" : Num(so))} | {(reveal is null ? "-" : $"{s.Tell(reveal)}, {reveal}")} |");
            foreach (var person in people)
            {
                var first = s.Model.BeliefsOf(person, prop)
                    .OrderBy(b => b.StoryKey).ThenBy(b => b.Id, StringComparer.Ordinal)
                    .FirstOrDefault(b => s.IsRight(new BeliefView(b.Id, b.Holder, b.Prop, b.Stance, b.Strength, b.StoryKey, b.Scene, b.Channel, b.Via)) == true);
                sb.Append(' ').Append(first is null ? "-" : Num(first.StoryKey) + (first.Scene is null ? " off page" : $" {first.Scene}")).Append(" |");
            }
            sb.Append('\n');
        }
        sb.Append("\nFacts:\n");
        foreach (var prop in props)
            sb.Append(CultureInfo.InvariantCulture, $"- {prop}: {Cell(s.Model.Proposition(prop)!.Text)}\n");
        return sb.ToString();
    }

    /// <summary>Each tracked object's path, as a Mermaid flowchart: where it was kept, in story order, and what moved it.</summary>
    private static string Objects(StoryState s)
    {
        static string Label(string text) => Nse.Text.Plain.OneLine(text).Replace("\"", "#quot;", StringComparison.Ordinal);
        var sb = new StringBuilder(Header(s, "Where things are kept"));
        if (s.TrackedObjects.Count == 0)
            return sb.Append("No object is tracked.\n").ToString();
        foreach (var obj in s.TrackedObjects)
        {
            var moves = s.Model.PlacementsOf(obj).OrderBy(p => p.StoryKey).ThenBy(p => p.Id, StringComparer.Ordinal).ToList();
            sb.Append(CultureInfo.InvariantCulture, $"## {Cell(s.Model.Entity(obj)?.Name ?? obj)} ({obj})\n\n```mermaid\nflowchart LR\n");
            for (var i = 0; i < moves.Count; i++)
            {
                var m = moves[i];
                sb.Append(CultureInfo.InvariantCulture, $"  n{i}[\"{Label(s.Model.Entity(m.Place)?.Name ?? m.Place)}\"]\n");
                if (i > 0)
                    sb.Append(CultureInfo.InvariantCulture, $"  n{i - 1} -->|\"{Num(m.StoryKey)} {Label(m.Cause)}{(m.Scene is null ? "" : " in " + Label(m.Scene))}\"| n{i}\n");
            }
            sb.Append("```\n\n");
            foreach (var m in moves)
            {
                var cause = s.Model.Events.TryGetValue(m.Cause, out var e) ? e.Summary : m.Cause;
                sb.Append(CultureInfo.InvariantCulture, $"- {Num(m.StoryKey)}: to {Cell(s.Model.Entity(m.Place)?.Name ?? m.Place)} ({m.Id}): {Cell(cause)}\n");
            }
            sb.Append('\n');
        }
        return sb.ToString();
    }

    /// <summary>
    /// How far the private worlds in each scene are out of line with what is so, with each other, and with the
    /// reader, on entry: Ryan's tellability, made countable. The raw counts grow with the cast, so each is also
    /// given per person present.
    /// </summary>
    private static string Divergence(StoryState s)
    {
        var sb = new StringBuilder(Header(s, "Divergence, scene by scene"));
        sb.Append("On entry to each scene, in the order told. Wrong: false or outdated beliefs held by people present. Reader ahead: facts the reader has been given that someone present does not know. Room ahead: facts someone present knows that the reader has not been given. Held back: embargoes in force. Per person: the first three summed, over the people present.\n\n");
        sb.Append("| Scene | Present | Wrong | Reader ahead | Room ahead | Held back | Per person |\n|---|---|---|---|---|---|---|\n");
        foreach (var t in Timed(s))
        {
            var key = s.Key(t.Id);
            var cast = s.CastHolders(t.Id).Select(c => c.Person).Distinct().ToList();
            var wrong = cast.Sum(p => s.BeliefsBefore(p, key).Values.Count(b => s.Classify(b, key) is "FALSE BELIEF" or "OUTDATED BELIEF"));
            var reader = s.ReaderBefore(t.Tell);
            var inPlay = s.InPlay(t.Id);
            bool ReaderHas(string prop) =>
                reader.TryGetValue(prop, out var v) && v.Stance == (s.Canon(prop) == "true" ? Stance.HoldsTrue : Stance.HoldsFalse);
            bool Knows(string person, string prop) =>
                s.BeliefBefore(person, prop, key) is { } b && s.IsRight(b, key) == true;
            var readerAhead = inPlay.Count(p => ReaderHas(p) && cast.Any(c => !Knows(c, p)));
            var roomAhead = inPlay.Count(p => !ReaderHas(p) && cast.Any(c => Knows(c, p)));
            var held = s.EmbargoesInForce(t.Id).Count;
            var per = cast.Count == 0 ? 0 : (wrong + readerAhead + roomAhead) / (double)cast.Count;
            sb.Append(CultureInfo.InvariantCulture,
                $"| {t.Tell}, {t.Id} | {cast.Count} | {wrong} | {readerAhead} | {roomAhead} | {held} | {per:0.0} |\n");
        }
        return sb.ToString();
    }
}
